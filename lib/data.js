const UPCOMING_REFERENCE_DATE = "2026-11-03";

export function getUpcomingCompetitions(count = 3) {
  const sorted = [...competitions].sort((a, b) => new Date(a.date) - new Date(b.date));
  const future = sorted.filter((c) => c.date >= UPCOMING_REFERENCE_DATE);
  const past = sorted.filter((c) => c.date < UPCOMING_REFERENCE_DATE).reverse();
  return [...future, ...past].slice(0, count);
}

